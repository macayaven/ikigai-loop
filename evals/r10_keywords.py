KEYWORD_RULES: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("iki-care", _compile(_CARE)),
    ("iki-family", _compile(_FAMILY)),
    ("iki-meeting", _compile(_MEETING)),
    ("iki-deep", _compile(_DEEP)),
    ("iki-social", _compile(_SOCIAL)),
    ("iki-rest", _compile(_REST)),
    ("iki-admin", _compile(_ADMIN)),
)

