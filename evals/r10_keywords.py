def _fold(text: str) -> str:
    folded = unicodedata.normalize("NFD", text.casefold())
    return "".join(char for char in folded if unicodedata.category(char) != "Mn")


def _compile(words: tuple[str, ...]) -> re.Pattern[str]:
    folded = sorted({_fold(word) for word in words})
    return re.compile(r"\b(?:{})\b".format("|".join(re.escape(w) for w in folded)))


